import { brand } from '@/config/brand'
import type { QuotationDocument, TariffSheet } from '@/domain/commercial/documents'
import { amountsText } from './quotationPdf'
import { dmy } from './layout'

export interface EmailDraft {
  subject: string
  body: string
  /** Suggested recipient (primary contact), if recorded. */
  to?: string
}

const firstName = (name?: string) => name?.trim().split(/\s+/)[0]

/** Prepared (not sent) email for a quotation, built from the document snapshot. */
export function quotationEmail(doc: QuotationDocument, senderName?: string): EmailDraft {
  const p = doc.party
  const greeting = p.contact ? `Hola ${firstName(p.contact.name)},` : `Estimado equipo de ${p.clientName}:`
  const services = doc.groups.map((g) => `• ${g.label}: ${amountsText(g.subtotal)}${g.lines.some((l) => l.special) ? ' (incluye subservicios especiales)' : ''}`)
  const project = [p.projectCode, p.beneficiary, p.route].filter(Boolean).join(' · ')
  const body = [
    greeting,
    '',
    `Te compartimos la cotización ${doc.number} v${doc.version} correspondiente al proyecto ${project}.`,
    '',
    'Servicios incluidos:',
    ...services,
    '',
    `Total: ${amountsText(doc.totals)}.`,
    `La propuesta es válida hasta el ${dmy(doc.validUntil)}.`,
    '',
    'Adjuntamos el PDF con el detalle de servicios, subservicios, cantidades y condiciones comerciales. Te pedimos que lo revises y, si estás de acuerdo, nos confirmes la aprobación para avanzar.',
    '',
    'Quedamos a disposición por cualquier consulta.',
    '',
    'Saludos,',
    senderName ?? p.accountManager?.name ?? '',
    brand.clientName,
  ]
  return { subject: `Cotización ${doc.number} v${doc.version} · ${p.projectCode} · ${p.clientName}`, body: body.join('\n').replace(/\n{3,}/g, '\n\n').trim(), to: p.contact?.email }
}

/** Prepared (not sent) email for the tariff in force. */
export function tariffEmail(sheet: TariffSheet, contact?: { name: string; email?: string }, senderName?: string): EmailDraft {
  const services = sheet.groups.map((g) => `• ${g.label} (${g.rows.length} ${g.rows.length === 1 ? 'precio' : 'precios'})`)
  const body = [
    contact ? `Hola ${firstName(contact.name)},` : `Estimado equipo de ${sheet.clientName}:`,
    '',
    `Te enviamos el tarifario de servicios de ${brand.clientName} vigente al ${dmy(sheet.date)}${sheet.requiresApproval ? ', con los precios aprobados' : ''}.`,
    '',
    'Incluye:',
    ...services,
    '',
    'En el PDF adjunto encontrás el detalle por servicio y subservicio, con unidades, monedas y vigencias. Te pedimos que lo revises y nos hagas llegar tus comentarios.',
    '',
    'Saludos,',
    senderName ?? '',
    brand.clientName,
  ]
  return { subject: `Tarifario ${brand.clientName} · ${sheet.clientName} · vigente al ${dmy(sheet.date)}`, body: body.join('\n').replace(/\n{3,}/g, '\n\n').trim(), to: contact?.email }
}

/** Triggers a browser download of generated bytes. */
export function downloadFile(bytes: Uint8Array, fileName: string, type = 'application/pdf') {
  const url = URL.createObjectURL(new Blob([bytes.slice() as Uint8Array<ArrayBuffer>], { type }))
  const a = document.createElement('a')
  a.href = url
  a.download = fileName
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}
